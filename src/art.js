// Hand-built 32-pixel character models. Shape, material and pose are independent
// for each species; the public 16*scale bounds keep every gameplay anchor stable.
const INK = '#152024';
const shineCache = new Map();
function shine(color) {
  if (!shineCache.has(color)) {
    const n = parseInt(color.slice(1),16), channels = [n >> 16, n >> 8 & 255, n & 255];
    shineCache.set(color, '#' + channels.map(c => Math.round(c + (245-c)*.6).toString(16).padStart(2,'0')).join(''));
  }
  return shineCache.get(color);
}
function painter(ctx, flash) {
  const color = c => flash && c !== INK && c !== '#232c30' ? shine(c) : c;
  return {
    r(x,y,w,h,c) {ctx.fillStyle=color(c);ctx.fillRect(Math.round(x),Math.round(y),w,h);},
    p(points,c) {ctx.fillStyle=color(c);ctx.beginPath();ctx.moveTo(...points[0]);for(const point of points.slice(1))ctx.lineTo(...point);ctx.closePath();ctx.fill();},
  };
}

